/**
 * توليد اختبارات تلقائي وفق آلية التقييم دون تعديل/حذف أي اختبار قائم.
 * يتخطى المتقدمين المسجّلين مسبقاً في اختبار نشط لنفس المسار.
 */
import { randomUUID } from 'crypto'
import { groupApplicants, resolveJobProfile, effectiveJobTitle, hasJobTitle } from '../shared/jobProfiles.js'
import { applicantAllowsTrack, ORAL_BUCKET_META, resolveOralBucket, tracksForApplicant } from '../shared/evaluationMatrix.js'

function fail(message, status = 400) {
  throw Object.assign(new Error(message), { status })
}

function groupConfigs(applicants, { questionCount = 20, includeShared = false } = {}) {
  return groupApplicants(applicants).map((g) => {
    const profile = resolveJobProfile(g.jobTitle) || { id: g.profileId || 'unclassified', specialty: 'unclassified' }
    return {
      key: g.key,
      profileId: profile.id || g.profileId || 'unclassified',
      specialty: profile.specialty || 'unclassified',
      jobLevel: 'intermediate',
      difficulty: 'mixed',
      questionCount,
      includeShared,
      skills: [],
      questionTypes: [],
    }
  })
}

function stamp() {
  const d = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

/**
 * @param {import('better-sqlite3').Database} db
 * @param {{ create: Function }} jobExams
 * @param {{ listApplicants: Function, insertExamRoster?: Function }} deps
 */
export function createAutoGenerateExamsService(db, jobExams, { listApplicants }) {
  function activeExamCoverKeys() {
    /** @type {Map<string, Set<string>>} applicantId -> set of cover keys */
    const map = new Map()
    const examCols = new Set(db.prepare('PRAGMA table_info(exams)').all().map((c) => c.name))
    const deletedClause = examCols.has('deleted_at') ? 'AND e.deleted_at IS NULL' : ''
    const rows = db
      .prepare(
        `SELECT r.applicant_id AS applicantId, e.category, e.oral_role AS oralRole, c.settings_json AS settings
         FROM exam_roster r
         JOIN exams e ON e.id = r.exam_id
         LEFT JOIN job_exam_configs c ON c.exam_id = e.id
         WHERE r.applicant_id IS NOT NULL
           ${deletedClause}
           AND COALESCE(e.active, 1) IN (0, 1)`,
      )
      .all()
    for (const row of rows) {
      if (!row.applicantId) continue
      let autoTrack = null
      try {
        autoTrack = row.settings ? JSON.parse(row.settings)?.autoTrack || null : null
      } catch {
        autoTrack = null
      }
      const keys = []
      if (row.category === 'oral') {
        keys.push(`oral:${row.oralRole || 'any'}`)
      } else if (row.category === 'theory') {
        keys.push(autoTrack === 'writing' || autoTrack === 'general' ? `theory:${autoTrack}` : 'theory:any')
      } else {
        keys.push(`${row.category}:any`)
      }
      if (!map.has(row.applicantId)) map.set(row.applicantId, new Set())
      const set = map.get(row.applicantId)
      for (const k of keys) set.add(k)
    }
    return map
  }

  function isCovered(coverMap, applicantId, coverKey) {
    const set = coverMap.get(applicantId)
    if (!set) return false
    if (set.has(coverKey)) return true
    // theory بدون وسم مسار يُعتبر مغطى لأي نظري
    if (coverKey.startsWith('theory:') && set.has('theory:any')) return true
    if (coverKey.startsWith('oral:') && set.has('oral:any')) return true
    return false
  }

  function filterFresh(applicants, coverMap, coverKey) {
    const included = []
    const skipped = []
    for (const a of applicants) {
      if (isCovered(coverMap, a.id, coverKey)) skipped.push({ id: a.id, name: a.name, reason: 'مسجّل مسبقاً في اختبار نشط لنفس المسار' })
      else included.push(a)
    }
    return { included, skipped }
  }

  function createTrackExam(user, { title, category, evaluationMode, applicants, coverKey, autoTrack, questionCount, includeShared }) {
    if (!applicants.length) return null
    const result = jobExams.create(user, {
      title,
      category,
      ...(evaluationMode ? { evaluationMode } : {}),
      applicantIds: applicants.map((a) => a.id),
      groups: groupConfigs(applicants, { questionCount, includeShared }),
    })
    // وسْم المسار في إعدادات كل اختبار ناتج
    const examItems = result.exams?.length ? result.exams : [result]
    for (const item of examItems) {
      const row = db.prepare('SELECT settings_json FROM job_exam_configs WHERE exam_id=?').get(item.exam.id)
      if (row) {
        let settings = {}
        try {
          settings = JSON.parse(row.settings_json || '{}')
        } catch {
          settings = {}
        }
        settings.autoGenerated = true
        settings.autoTrack = autoTrack || settings.autoTrack || null
        settings.autoCoverKey = coverKey
        settings.autoGeneratedAt = new Date().toISOString()
        db.prepare('UPDATE job_exam_configs SET settings_json=? WHERE exam_id=?').run(JSON.stringify(settings), item.exam.id)
      }
    }
    return result
  }

  function parseExtra(raw) {
    try {
      return raw ? JSON.parse(raw) : {}
    } catch {
      return {}
    }
  }

  /**
   * يعيد توزيع روستر الاختبارات الشفهية القائمة حسب التخصص الصحيح
   * (فني / برمجة / شبكات) دون حذف أي اختبار — فقط نقل المتقدمين بين الاختبارات.
   */
  function repairOralSpecialtyAssignments(user) {
    const examCols = new Set(db.prepare('PRAGMA table_info(exams)').all().map((c) => c.name))
    const deletedClause = examCols.has('deleted_at') ? 'AND deleted_at IS NULL' : ''
    const oralExams = db
      .prepare(`SELECT * FROM exams WHERE category='oral' ${deletedClause} ORDER BY created_at DESC`)
      .all()
    if (!oralExams.length) return { moved: 0, created: 0, warnings: [] }

    const byRole = new Map()
    for (const exam of oralExams) {
      const role = exam.oral_role || null
      if (!role) continue
      if (!byRole.has(role)) byRole.set(role, [])
      byRole.get(role).push(exam)
    }

    const pickTarget = (role) => {
      const list = byRole.get(role) || []
      // فضّل اختبار التوليد التلقائي لنفس التخصص إن وُجد
      const auto = list.find((e) => /توليد تلقائي|شفهي/.test(e.title || ''))
      return auto || list[0] || null
    }

    const ensureTarget = (role) => {
      let target = pickTarget(role)
      if (target) return target
      // هيكل اختبار فارغ ثم ننقل الروستر إليه — بدون create() لتجنّب التكرار والقفل المتداخل
      const meta = Object.values(ORAL_BUCKET_META).find((m) => m.oralRole === role) || ORAL_BUCKET_META.technician
      const bucketKey = Object.keys(ORAL_BUCKET_META).find((k) => ORAL_BUCKET_META[k].oralRole === role) || 'technician'
      const examId = `exam-${randomUUID()}`
      const now = new Date().toISOString()
      const level = role === 'technician' ? 'technician' : 'engineer'
      db.prepare(
        `INSERT INTO exams(id,title,category,level,oral_role,capacity,question_count,username,password_hash,password_plain,question_ids,questions_json,created_by,created_at,active)
         VALUES (?,?,?,?,?,?,?,?,'','','[]','[]',?,?,1)`,
      ).run(
        examId,
        `توليد تلقائي — شفهي — ${meta.label} — إعادة فرز`,
        'oral',
        level,
        role,
        0,
        20,
        `internal_${randomUUID()}`,
        user?.username || 'admin',
        now,
      )
      db.prepare('INSERT INTO job_exam_configs VALUES (?, ?)').run(
        examId,
        JSON.stringify({
          version: 1,
          titleSource: 'jobTitle',
          evaluationMode: 'qr',
          groups: [],
          oralBucket: bucketKey,
          autoGenerated: true,
          autoTrack: meta.trackId,
          repairedAt: now,
        }),
      )
      target = db.prepare('SELECT * FROM exams WHERE id=?').get(examId)
      if (!byRole.has(role)) byRole.set(role, [])
      byRole.get(role).unshift(target)
      return target
    }

    const moves = []
    const warnings = []
    for (const exam of oralExams) {
      const rows = db.prepare('SELECT * FROM exam_roster WHERE exam_id=?').all(exam.id)
      for (const row of rows) {
        const applicant = {
          id: row.applicant_id || row.id,
          jobTitle: row.job_title || '',
          extra: parseExtra(row.extra_json),
        }
        const bucket = resolveOralBucket(applicant)
        if (!bucket || bucket === 'admin') continue
        const wantRole = ORAL_BUCKET_META[bucket]?.oralRole
        if (!wantRole) continue
        if (exam.oral_role && exam.oral_role === wantRole) continue
        moves.push({ row, fromExam: exam, wantRole, bucket, applicant })
      }
    }

    if (!moves.length) return { moved: 0, created: 0, warnings: [] }

    let createdCount = 0
    const tx = db.transaction(() => {
      const rolesNeeded = [...new Set(moves.map((m) => m.wantRole))]
      for (const role of rolesNeeded) {
        if (pickTarget(role)) continue
        ensureTarget(role)
        createdCount += 1
      }

      for (const m of moves) {
        const target = pickTarget(m.wantRole)
        if (!target) {
          warnings.push(`تعذر إيجاد اختبار لـ ${m.wantRole} لنقل ${m.row.name}`)
          continue
        }
        if (target.id === m.fromExam.id) continue
        db.prepare('UPDATE exam_roster SET exam_id=? WHERE id=?').run(target.id, m.row.id)
        db.prepare('UPDATE exam_question_sets SET exam_id=? WHERE roster_id=?').run(target.id, m.row.id)
      }

      const touched = new Set(moves.flatMap((m) => [m.fromExam.id, pickTarget(m.wantRole)?.id].filter(Boolean)))
      for (const examId of touched) {
        const n = db.prepare('SELECT COUNT(*) AS n FROM exam_roster WHERE exam_id=?').get(examId).n
        db.prepare('UPDATE exams SET capacity=? WHERE id=?').run(n, examId)
      }
    })
    tx()

    return { moved: moves.length, created: createdCount, warnings }
  }

  /**
   * توليد اختبارات للمتقدمين المحددين (أو الكل إن لم تُمرَّر معرفات).
   */
  function generate(user, body = {}) {
    if (user?.role !== 'admin') fail('توليد الاختبارات التلقائي متاح للمسؤول العام فقط', 403)

    // أولاً: أصلح خلط التخصصات في اختبارات شفهية قائمة
    let repair = { moved: 0, created: 0, warnings: [] }
    try {
      repair = repairOralSpecialtyAssignments(user)
    } catch (err) {
      repair = { moved: 0, created: 0, warnings: [err.message || 'تعذر إصلاح فرز الشفهي'] }
    }

    const all = listApplicants()
    const idFilter = Array.isArray(body.applicantIds) && body.applicantIds.length
      ? new Set(body.applicantIds.map(String))
      : null
    const interviewFilter = body.interviewType ? String(body.interviewType).trim() : ''

    let pool = all.filter((a) => hasJobTitle(a))
    if (idFilter) pool = pool.filter((a) => idFilter.has(a.id))
    if (interviewFilter) {
      pool = pool.filter((a) => String(a.extra?.['نوع المقابلة'] || '').trim() === interviewFilter)
    }

    const missingTitle = (idFilter
      ? all.filter((a) => idFilter.has(a.id))
      : all
    ).filter((a) => !hasJobTitle(a))

    if (!pool.length) {
      fail(
        missingTitle.length
          ? `لا متقدمين بمسمى عمل جاهز للتوليد (${missingTitle.length} بلا مسمى). صنّف المسميات أولاً.`
          : 'لا متقدمين لتوليد الاختبارات',
      )
    }

    const coverMap = activeExamCoverKeys()
    const batch = stamp()
    const prefix = String(body.titlePrefix || 'توليد تلقائي').trim() || 'توليد تلقائي'
    const questionCount = Math.max(1, Math.min(100, Number(body.questionCount) || 20))
    const created = []
    const skipped = []
    const warnings = []

    if (missingTitle.length) {
      warnings.push(`تُجُوهل ${missingTitle.length} متقدم بلا مسمى عمل — لن يُدرجوا حتى يُصنَّفوا.`)
    }

    const plans = [
      {
        trackId: 'general',
        category: 'theory',
        evaluationMode: null,
        autoTrack: 'general',
        coverKey: 'theory:general',
        title: `${prefix} — عام — ${batch}`,
        includeShared: false,
        pick: (list) => list.filter((a) => applicantAllowsTrack(a, 'general')),
      },
      {
        trackId: 'writing',
        category: 'theory',
        evaluationMode: null,
        autoTrack: 'writing',
        coverKey: 'theory:writing',
        title: `${prefix} — اختبار كتابي — ${batch}`,
        includeShared: false,
        pick: (list) => list.filter((a) => applicantAllowsTrack(a, 'writing')),
      },
    ]

    warnings.push(
      'التوليد التلقائي ينشئ اختبارات العام والاختبار الكتابي فقط. شفهي/قيادة/شخصية: وزّع المتقدمين على اللجان من صفحة اللجان، ثم تنشئ اللجنة الاختبار وتختار الطريقة.',
    )

    for (const plan of plans) {
      const candidates = plan.pick(pool)
      const { included, skipped: skipRows } = filterFresh(candidates, coverMap, plan.coverKey)
      skipped.push(...skipRows.map((s) => ({ ...s, track: plan.trackId })))
      if (!included.length) {
        if (candidates.length) warnings.push(`${plan.trackId}: كل المتقدمين مغطّون مسبقاً — لم يُنشأ اختبار جديد.`)
        continue
      }
      try {
        const result = createTrackExam(user, {
          title: plan.title,
          category: plan.category,
          evaluationMode: plan.evaluationMode,
          applicants: included,
          coverKey: plan.coverKey,
          autoTrack: plan.autoTrack,
          questionCount,
          includeShared: plan.includeShared,
        })
        if (!result) continue
        const items = result.exams?.length ? result.exams : [result]
        for (const item of items) {
          created.push({
            id: item.exam.id,
            title: item.exam.title,
            category: item.exam.category,
            oralRole: item.exam.oral_role || null,
            track: plan.trackId,
            rosterCount: item.roster?.length || 0,
            pendingQuestions: item.exam.active === 0,
            warnings: item.warnings || [],
          })
          // حدّث غطاء الذاكرة حتى لا يُعاد إدراجهم في نفس التشغيل
          for (const a of included) {
            if (!coverMap.has(a.id)) coverMap.set(a.id, new Set())
            coverMap.get(a.id).add(plan.coverKey)
          }
        }
        warnings.push(...(result.warnings || []).filter((w) => typeof w === 'string'))
      } catch (err) {
        warnings.push(`${plan.title}: ${err.message || 'تعذر الإنشاء'}`)
      }
    }

    // ملخص فرز حسب المسمى/الصنف
    const sortSummary = []
    const byStream = new Map()
    for (const a of pool) {
      const tracks = tracksForApplicant(a)
      const streamLabel = tracks.length
        ? (a.extra?.['نوع المقابلة'] === 'خارجية' ? 'اختصاصي/إداري' : '')
        : ''
      void streamLabel
      const key = effectiveJobTitle(a) || 'بلا مسمى'
      if (!byStream.has(key)) byStream.set(key, { jobTitle: key, count: 0, tracks: tracks.map((t) => t.label) })
      byStream.get(key).count += 1
    }
    for (const row of byStream.values()) sortSummary.push(row)
    sortSummary.sort((a, b) => b.count - a.count)

    if (repair.moved) {
      warnings.unshift(`أُعيد فرز ${repair.moved} متقدم شفهي إلى اختبار تخصصهم الصحيح (فني/برمجة/شبكات).`)
    }
    if (repair.created) {
      warnings.unshift(`أُنشئ ${repair.created} اختبار شفهي ناقص أثناء إعادة الفرز.`)
    }
    warnings.push(...(repair.warnings || []))

    return {
      ok: true,
      createdCount: created.length,
      skippedCount: skipped.length,
      considered: pool.length,
      missingTitleCount: missingTitle.length,
      repairedMoves: repair.moved,
      exams: created,
      skipped: skipped.slice(0, 200),
      warnings: [...new Set(warnings)],
      sortSummary: sortSummary.slice(0, 100),
    }
  }

  return { generate, repairOralSpecialtyAssignments }
}
